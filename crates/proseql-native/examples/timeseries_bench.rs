/// Bump when the generated bytes change so stale caches are not reused.
const GENERATOR_VERSION: u32 = 1;
const COLLECTION: &str = "heartrate";
const LINE_PREFIX: &str = "TSBENCH ";
const MS_PER_DAY: i64 = 86_400_000;
const MS_PER_HOUR: i64 = 3_600_000;

type BoxError = Box<dyn std::error::Error + Send + Sync>;

// ── Modes ────────────────────────────────────────────────────────────────────

/// Cumulative feature sets, one per step of the time-series work.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Mode {
    /// Step 1: today's behaviour. `PartitionKey::Field { month }`, rewrite path.
    Baseline,
    /// Step 2: `append_only: true` + `duplicate_ids: ignore_identical`. Creates
    /// append lines instead of rewriting the partition.
    Append,
    /// Step 3: step 2 + `PartitionKey::TimeBucket { timestamp, Month }`. Rows
    /// have no `month` field.
    TimeBucket,
    /// Step 4: step 3 + `ordered_indexes: ["timestamp"]`.
    Ordered,
    /// Step 5: step 4 + `lazy_partitions` for the heart-rate source.
    Lazy,
}

#[derive(Debug, Clone, Copy)]
struct Features {
    append_only: bool,
    time_bucket: bool,
    ordered_index: bool,
    lazy: bool,
}

impl Mode {
    fn parse(value: &str) -> Result<Self, BoxError> {
        Ok(match value {
            "baseline" => Mode::Baseline,
            "append" => Mode::Append,
            "timebucket" => Mode::TimeBucket,
            "ordered" => Mode::Ordered,
            "lazy" => Mode::Lazy,
            other => return Err(format!("unknown --mode '{other}'").into()),
        })
    }

    fn name(self) -> &'static str {
        match self {
            Mode::Baseline => "baseline",
            Mode::Append => "append",
            Mode::TimeBucket => "timebucket",
            Mode::Ordered => "ordered",
            Mode::Lazy => "lazy",
        }
    }

    fn features(self) -> Features {
        let step = self as u8;
        Features {
            append_only: step >= Mode::Append as u8,
            time_bucket: step >= Mode::TimeBucket as u8,
            ordered_index: step >= Mode::Ordered as u8,
            lazy: step >= Mode::Lazy as u8,
        }
    }
}

