fn parse_args() -> Result<Args, BoxError> {
    let mut args = Args {
        rows: vec![140_000, 1_000_000, 10_000_000],
        years: 10.0,
        start: "2016-01-01".into(),
        seed: 20_261_020,
        mode: Mode::Baseline,
        inserts: 1000,
        insert_budget_secs: 600.0,
        query_reps: 20,
        data_dir: default_data_dir(),
        max_rss_mb: 0,
        min_available_mb: 1024,
        max_loaded_partitions: 4,
        keep: false,
        child_work: None,
    };
    let mut iter = std::env::args().skip(1);
    while let Some(flag) = iter.next() {
        let mut value = || iter.next().ok_or_else(|| format!("{flag} needs a value"));
        match flag.as_str() {
            "--rows" => {
                args.rows = value()?
                    .split(',')
                    .map(|part| part.trim().replace('_', "").parse::<u64>())
                    .collect::<Result<_, _>>()?
            }
            "--years" => args.years = value()?.parse()?,
            "--start" => args.start = value()?,
            "--seed" => args.seed = value()?.parse()?,
            "--mode" => args.mode = Mode::parse(&value()?)?,
            "--inserts" => args.inserts = value()?.parse()?,
            "--insert-budget-secs" => args.insert_budget_secs = value()?.parse()?,
            "--query-reps" => args.query_reps = value()?.parse()?,
            "--data-dir" => args.data_dir = PathBuf::from(value()?),
            "--max-rss-mb" => args.max_rss_mb = value()?.parse()?,
            "--min-available-mb" => args.min_available_mb = value()?.parse()?,
            "--max-loaded-partitions" => args.max_loaded_partitions = value()?.parse()?,
            "--keep" => args.keep = true,
            "--child-work" => args.child_work = Some(PathBuf::from(value()?)),
            "-h" | "--help" => {
                println!("{USAGE}");
                std::process::exit(0);
            }
            other => return Err(format!("unknown argument '{other}'\n{USAGE}").into()),
        }
    }
    if args.rows.is_empty() || args.rows.contains(&0) {
        return Err("--rows needs positive sizes".into());
    }
    if args.years.is_nan() || args.years <= 0.0 {
        return Err("--years must be positive".into());
    }
    if args.query_reps == 0 {
        return Err("--query-reps must be at least 1".into());
    }
    if args.max_rss_mb == 0 {
        let available = mem_available_mb().unwrap_or(4096);
        args.max_rss_mb = available.saturating_sub(1024).max(256);
    }
    Ok(args)
}

/// A stable location outside the checkout. `nix develop` points `TMPDIR` at a
/// per-shell directory, so the cache prefers `/var/tmp`, which also survives
/// reboots and is disk-backed on most systems.
fn default_data_dir() -> PathBuf {
    if let Some(dir) = std::env::var_os("PROSEQL_BENCH_DATA_DIR") {
        return PathBuf::from(dir);
    }
    let var_tmp = Path::new("/var/tmp");
    let base = if var_tmp.is_dir() {
        var_tmp.to_path_buf()
    } else {
        std::env::temp_dir()
    };
    base.join("proseql-timeseries-bench")
}

fn main() {
    let result = parse_args().and_then(|args| match &args.child_work {
        Some(work) => child(&args, work),
        None => parent(&args),
    });
    if let Err(error) = result {
        eprintln!("timeseries_bench: {error}");
        std::process::exit(1);
    }
}

// ── Dataset layout ───────────────────────────────────────────────────────────

/// Deterministic description of one dataset. The generator, the child and the
/// insert workload all derive timestamps from it, so no data is passed around.
#[derive(Debug, Clone, Copy)]
struct Dataset {
    rows: u64,
    start_ms: i64,
    span_ms: i64,
    seed: u64,
    /// Rows carry the redundant `month` field (every mode before timebucket).
    month_field: bool,
}

impl Dataset {
    fn new(args: &Args, rows: u64) -> Result<Self, BoxError> {
        let start_ms = parse_date_ms(&args.start)?;
        let span_ms = (args.years * 365.2425 * MS_PER_DAY as f64) as i64;
        if span_ms / (rows as i64) < 2 {
            return Err("--years is too short for the requested rows".into());
        }
        Ok(Self {
            rows,
            start_ms,
            span_ms,
            seed: args.seed,
            month_field: !args.mode.features().time_bucket,
        })
    }

    fn cache_key(&self) -> String {
        format!(
            "v{GENERATOR_VERSION}-rows{}-start{}-span{}-seed{}{}",
            self.rows,
            self.start_ms,
            self.span_ms,
            self.seed,
            if self.month_field { "" } else { "-nomonth" }
        )
    }

    fn interval_ms(&self) -> i64 {
        self.span_ms / self.rows as i64
    }

    fn end_ms(&self) -> i64 {
        self.start_ms + self.span_ms
    }

    /// Row `i`: an even slot plus up to half a slot of jitter. Strictly
    /// increasing, so IDs derived from timestamps are unique.
    fn row(&self, i: u64, rng: &mut SplitMix64) -> Value {
        let slot = self.start_ms + (i as i128 * self.span_ms as i128 / self.rows as i128) as i64;
        let jitter = rng.below((self.interval_ms() / 2).max(1) as u64) as i64;
        synthetic_row(slot + jitter, rng, self.month_field)
    }

    /// Timestamps for the append workload, after `last_ms` (the last generated
    /// row, which the child reads from the last partition file).
    fn insert_timestamps(&self, last_ms: i64, count: usize) -> Vec<i64> {
        // Stay inside the last generated month so every append targets an
        // existing, full-size partition.
        let month_end = month_end_ms(last_ms);
        let room = (month_end.min(self.end_ms()) - last_ms - 1).max(count as i64 + 1);
        let step = (room / (count as i64 + 1)).clamp(1, 1000);
        (1..=count as i64).map(|i| last_ms + i * step).collect()
    }
}

/// One heart-rate sample. `month_field` adds the redundant `YYYY-MM` field that
/// `PartitionKey::Field` needs; time-bucket keys derive it from `timestamp`.
fn synthetic_row(ms: i64, rng: &mut SplitMix64, month_field: bool) -> Value {
    let iso = format_iso_ms(ms);
    let (source, low, high) = match rng.below(100) {
        0..=39 => ("awake", 58, 100),
        40..=64 => ("rest", 48, 72),
        65..=84 => ("live", 55, 115),
        85..=94 => ("workout", 95, 175),
        _ => ("session", 52, 90),
    };
    let bpm = low + rng.below((high - low + 1) as u64) as i64;
    let mut row = json!({
        "id": format!("heartrate:{iso}"),
        "timestamp": iso,
        "bpm": bpm,
        "source": source,
    });
    if month_field {
        row["month"] = json!(&iso[..7]);
    }
    row
}

/// Generate the dataset once; later runs with the same key reuse it. Files
/// match the JSONL encoder byte for byte: compact lines in schema order,
/// joined by `\n`, with no trailing newline.
fn ensure_dataset(args: &Args, dataset: &Dataset) -> Result<PathBuf, BoxError> {
    let dir = args.data_dir.join("cache").join(dataset.cache_key());
    let marker = dir.join(".complete");
    let root = dir.join(COLLECTION);
    if marker.exists() {
        eprintln!(
            "[tsbench] rows={} using cached data {}",
            dataset.rows,
            dir.display()
        );
        return Ok(root);
    }
    if dir.exists() {
        fs::remove_dir_all(&dir)?;
    }
    fs::create_dir_all(&root)?;
    let started = Instant::now();
    let mut rng = SplitMix64(dataset.seed ^ dataset.rows);
    let mut current: Option<(String, BufWriter<fs::File>)> = None;
    let mut partitions = 0u64;
    for i in 0..dataset.rows {
        let row = dataset.row(i, &mut rng);
        let month = row["timestamp"].as_str().expect("timestamp")[..7].to_owned();
        let line = serde_json::to_string(&row)?;
        match &mut current {
            Some((open, writer)) if *open == month => {
                writer.write_all(b"\n")?;
                writer.write_all(line.as_bytes())?;
            }
            _ => {
                if let Some((_, mut writer)) = current.take() {
                    writer.flush()?;
                }
                let file = fs::File::create(root.join(format!("{month}.jsonl")))?;
                let mut writer = BufWriter::with_capacity(1 << 20, file);
                writer.write_all(line.as_bytes())?;
                current = Some((month, writer));
                partitions += 1;
            }
        }
    }
    if let Some((_, mut writer)) = current.take() {
        writer.flush()?;
    }
    fs::write(
        &marker,
        json!({"rows": dataset.rows, "partitions": partitions, "seed": dataset.seed}).to_string(),
    )?;
    eprintln!(
        "[tsbench] rows={} generated {partitions} partitions in {:.1}s at {}",
        dataset.rows,
        started.elapsed().as_secs_f64(),
        dir.display()
    );
    Ok(root)
}

fn copy_dataset(source: &Path, target: &Path) -> Result<(), BoxError> {
    if target.exists() {
        fs::remove_dir_all(target)?;
    }
    fs::create_dir_all(target)?;
    for entry in fs::read_dir(source)? {
        let entry = entry?;
        // `fs::copy` uses copy_file_range, which reflinks on btrfs/xfs.
        fs::copy(entry.path(), target.join(entry.file_name()))?;
    }
    Ok(())
}

// ── Parent ───────────────────────────────────────────────────────────────────

fn parent(args: &Args) -> Result<(), BoxError> {
    require_supported(args.mode.features())?;
    eprintln!(
        "[tsbench] mode={} rows={:?} years={} max_rss_mb={} data_dir={}",
        args.mode.name(),
        args.rows,
        args.years,
        args.max_rss_mb,
        args.data_dir.display()
    );
    let exe = std::env::current_exe()?;
    let mut results = Vec::new();
    for &rows in &args.rows {
        let dataset = Dataset::new(args, rows)?;
        let cached = ensure_dataset(args, &dataset)?;
        let work = args
            .data_dir
            .join(format!("work-{}-{rows}", std::process::id()));
        copy_dataset(&cached, &work.join(COLLECTION))?;
        let mut child_args: Vec<String> = vec![
            "--rows".into(),
            rows.to_string(),
            "--years".into(),
            args.years.to_string(),
            "--start".into(),
            args.start.clone(),
            "--seed".into(),
            args.seed.to_string(),
            "--mode".into(),
            args.mode.name().into(),
            "--inserts".into(),
            args.inserts.to_string(),
            "--insert-budget-secs".into(),
            args.insert_budget_secs.to_string(),
            "--query-reps".into(),
            args.query_reps.to_string(),
            "--max-rss-mb".into(),
            args.max_rss_mb.to_string(),
            "--min-available-mb".into(),
            args.min_available_mb.to_string(),
            "--max-loaded-partitions".into(),
            args.max_loaded_partitions.to_string(),
            "--child-work".into(),
        ];
        child_args.push(work.to_string_lossy().into_owned());
        let mut process = Command::new(&exe)
            .args(&child_args)
            .stdout(Stdio::piped())
            .stderr(Stdio::inherit())
            .spawn()?;
        let mut report: Option<Value> = None;
        let stdout = process.stdout.take().expect("piped stdout");
        for line in BufReader::new(stdout).lines() {
            let line = line?;
            if let Some(payload) = line.strip_prefix(LINE_PREFIX) {
                println!("{line}");
                report = serde_json::from_str(payload).ok();
            } else {
                eprintln!("{line}");
            }
        }
        let status = process.wait()?;
        if report.is_none() {
            let failed = json!({
                "mode": args.mode.name(),
                "rows": rows,
                "status": "failed",
                "exit": status.code(),
                "note": "child produced no report (killed by a signal, e.g. the OOM killer, if exit is null)",
            });
            println!("{LINE_PREFIX}{failed}");
            report = Some(failed);
        }
        results.push(report.expect("report"));
        if !args.keep {
            fs::remove_dir_all(&work)?;
        }
    }
    print_table(&results);
    Ok(())
}

fn print_table(results: &[Value]) {
    let cell = |report: &Value, key: &str| match report.get(key) {
        Some(Value::Number(number)) => number
            .as_f64()
            .map(|value| {
                if value.fract() == 0.0 {
                    format!("{value:.0}")
                } else {
                    format!("{value:.2}")
                }
            })
            .unwrap_or_default(),
        Some(Value::String(text)) => text.clone(),
        Some(Value::Bool(flag)) => flag.to_string(),
        _ => "—".into(),
    };
    println!();
    println!(
        "| rows | partitions | open ms | RSS after open MiB | peak RSS MiB | inserts | insert median ms | insert p95 ms | bytes written/insert | bytes read/insert | file growth/insert | prefix kept | 1h query median ms | rows | partitions loaded | index | newest-100 median ms | newest-100 index | status |"
    );
    println!("|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|---|---:|---:|---:|---|---:|---|---|");
    for report in results {
        let keys = [
            "rows",
            "partitions",
            "open_ms",
            "rss_after_open_mb",
            "peak_rss_mb",
            "inserts_done",
            "insert_median_ms",
            "insert_p95_ms",
            "insert_bytes_written_median",
            "insert_bytes_read_median",
            "insert_file_growth_median",
            "insert_prefix_preserved",
            "query_median_ms",
            "query_rows",
            "query_partitions_loaded",
            "query_index_used",
            "sorted_query_median_ms",
            "sorted_query_index_used",
            "status",
        ];
        let cells: Vec<String> = keys.iter().map(|key| cell(report, key)).collect();
        println!("| {} |", cells.join(" | "));
    }
}

// ── Child ────────────────────────────────────────────────────────────────────

type Report = Arc<Mutex<Map<String, Value>>>;

fn record(report: &Report, key: &str, value: Value) {
    report
        .lock()
        .expect("report lock")
        .insert(key.to_owned(), value);
}

static CHILD_START: OnceLock<Instant> = OnceLock::new();

fn elapsed_ms() -> f64 {
    ms(CHILD_START.get_or_init(Instant::now).elapsed())
}

/// Record the current phase and when it started, so an abort can say where
/// and after how long it stopped.
fn set_phase(report: &Report, phase: &str) {
    record(report, "phase", json!(phase));
    record(report, "phase_started_ms", json!(elapsed_ms()));
}

fn emit(report: &Report) {
    let map = report.lock().expect("report lock").clone();
    println!("{LINE_PREFIX}{}", Value::Object(map));
    let _ = std::io::stdout().flush();
}

/// Abort the child with partial numbers when RSS passes the limit, or when
/// the machine's `MemAvailable` drops below the floor. The floor matters on a
/// shared machine: other processes can use the memory the RSS limit assumed
/// was free, and the kernel OOM killer would act before the RSS limit fires.
fn start_rss_watchdog(report: Report, limit_mb: u64, floor_mb: u64) {
    std::thread::spawn(move || loop {
        let rss = proc_status_mb("VmRSS:");
        let available = mem_available_mb();
        let reason = match (rss, available) {
            (Some(rss), _) if rss > limit_mb => Some(format!(
                "rss {rss} MiB exceeded --max-rss-mb {limit_mb}"
            )),
            (rss, Some(available)) if available < floor_mb => Some(format!(
                "MemAvailable {available} MiB fell below --min-available-mb {floor_mb} (rss {} MiB)",
                rss.unwrap_or(0)
            )),
            _ => None,
        };
        if let Some(reason) = reason {
            let mut map = report.lock().expect("report lock");
            map.insert("status".into(), json!("aborted"));
            map.insert("reason".into(), json!(reason));
            map.insert("peak_rss_mb".into(), json!(proc_status_mb("VmHWM:")));
            map.insert("mem_available_at_abort_mb".into(), json!(available));
            let now = elapsed_ms();
            let phase_started = map
                .get("phase_started_ms")
                .and_then(Value::as_f64)
                .unwrap_or(0.0);
            map.insert("elapsed_ms".into(), json!(now));
            map.insert("phase_elapsed_ms".into(), json!(now - phase_started));
            println!("{LINE_PREFIX}{}", Value::Object(map.clone()));
            let _ = std::io::stdout().flush();
            std::process::exit(3);
        }
        std::thread::sleep(Duration::from_millis(10));
    });
}

fn child(args: &Args, work: &Path) -> Result<(), BoxError> {
    CHILD_START.get_or_init(Instant::now);
    let rows = args.rows[0];
    let dataset = Dataset::new(args, rows)?;
    let features = args.mode.features();
    require_supported(features)?;
    let root = work.join(COLLECTION);
    let report: Report = Arc::new(Mutex::new(Map::new()));
    record(&report, "mode", json!(args.mode.name()));
    record(&report, "rows", json!(rows));
    record(&report, "years", json!(args.years));
    record(&report, "seed", json!(args.seed));
    record(&report, "max_rss_mb", json!(args.max_rss_mb));
    record(&report, "min_available_mb", json!(args.min_available_mb));
    record(
        &report,
        "mem_available_at_start_mb",
        json!(mem_available_mb()),
    );
    record(&report, "status", json!("running"));
    start_rss_watchdog(Arc::clone(&report), args.max_rss_mb, args.min_available_mb);

    let mut partition_paths: Vec<PathBuf> = fs::read_dir(&root)?
        .map(|entry| entry.map(|entry| entry.path()))
        .collect::<Result<_, _>>()?;
    partition_paths.sort();
    let total_bytes: u64 = partition_paths
        .iter()
        .map(|path| fs::metadata(path).map(|meta| meta.len()))
        .sum::<Result<_, _>>()?;
    record(&report, "partitions", json!(partition_paths.len()));
    record(&report, "data_bytes", json!(total_bytes));
    record(
        &report,
        "rss_before_open_mb",
        json!(proc_status_mb("VmRSS:")),
    );

    // Open.
    set_phase(&report, "open");
    let host = Arc::new(CountingHost::new()?);
    let config = runtime_config(&root, features)?;
    let options = runtime_options(features, args)?;
    let started = Instant::now();
    let runtime =
        NativeRuntime::open_sources_with_host(config, host.clone(), options).map_err(tag)?;
    let open_ms = ms(started.elapsed());
    let opened = host.take();
    let loaded_records = runtime
        .read(|db| Ok(db.collection(COLLECTION).map_or(0, |c| c.len())))
        .map_err(tag)?;
    record(&report, "open_ms", json!(open_ms));
    // Peak through open (VmHWM) and what stays resident afterwards (VmRSS).
    record(
        &report,
        "rss_after_open_mb",
        json!(proc_status_mb("VmHWM:")),
    );
    record(
        &report,
        "rss_resident_after_open_mb",
        json!(proc_status_mb("VmRSS:")),
    );
    record(&report, "records_loaded", json!(loaded_records));
    record(
        &report,
        "open_partitions_read",
        json!(opened.partition_paths(&root)),
    );
    record(&report, "open_bytes_read", json!(opened.bytes_read));
    eprintln!(
        "[tsbench] rows={rows} open {open_ms:.0} ms, {loaded_records} records, RSS {:?} MiB",
        proc_status_mb("VmHWM:")
    );

    record(
        &report,
        "partition_key",
        json!(partition_key_label(features)),
    );
    record(&report, "ordered_indexes", json!(ordered_indexes(features)));

    // One-hour range query, aligned to an hour in the middle of the data.
    set_phase(&report, "query");
    let from = (dataset.start_ms + dataset.span_ms / 2) / MS_PER_HOUR * MS_PER_HOUR;
    let to = from + MS_PER_HOUR;
    let filter = json!({"timestamp": {"$gte": format_iso_ms(from), "$lt": format_iso_ms(to)}});
    record(&report, "query_from", json!(format_iso_ms(from)));
    let mut timings = Vec::with_capacity(args.query_reps);
    let mut query_rows = 0;
    host.take();
    for _ in 0..args.query_reps {
        let input = QueryInput {
            r#where: Some(filter.clone()),
            ..QueryInput::default()
        };
        let started = Instant::now();
        let result = run_query(&runtime, features, input)?;
        timings.push(ms(started.elapsed()));
        query_rows = result.len();
    }
    let queried = host.take();
    let one_hour = QueryInput {
        r#where: Some(filter.clone()),
        ..QueryInput::default()
    };
    let (partitions_loaded, stats) = query_stats(&runtime, features, &one_hour, &opened, &root)?;
    record(&report, "query_reps", json!(args.query_reps));
    record(&report, "query_first_ms", json!(timings[0]));
    record(&report, "query_median_ms", json!(median(&mut timings)));
    record(&report, "query_rows", json!(query_rows));
    record(&report, "query_partitions_loaded", json!(partitions_loaded));
    record(
        &report,
        "query_partition_reads",
        json!(queried.partition_paths(&root)),
    );
    record(&report, "query_index_used", json!(stats.index_used));
    record(&report, "query_candidate_rows", json!(stats.candidate_rows));

    // Supplementary: a window of one sample slot (span / rows) at the same
    // start, so every size returns about one row. The one-hour window returns
    // more rows as density grows; this one separates per-row cost from
    // history size.
    let slot_filter = json!({"timestamp": {"$gte": format_iso_ms(from), "$lt": format_iso_ms(from + dataset.interval_ms())}});
    let mut slot_timings = Vec::with_capacity(args.query_reps);
    let mut slot_rows = 0;
    for _ in 0..args.query_reps {
        let input = QueryInput {
            r#where: Some(slot_filter.clone()),
            ..QueryInput::default()
        };
        let started = Instant::now();
        slot_rows = run_query(&runtime, features, input)?.len();
        slot_timings.push(ms(started.elapsed()));
    }
    record(
        &report,
        "slot_query_window_ms",
        json!(dataset.interval_ms()),
    );
    record(
        &report,
        "slot_query_median_ms",
        json!(median(&mut slot_timings)),
    );
    record(&report, "slot_query_rows", json!(slot_rows));

    // Newest 100 samples: a sort on the timestamp with a limit, which an
    // ordered index answers without sorting the collection. Lazy mode refuses
    // full scans, so there it is limited to the last month of data.
    let newest_filter = features.lazy.then(
        || json!({"timestamp": {"$gte": format_iso_ms(month_start_ms(dataset.end_ms() - 1))}}),
    );
    record(&report, "sorted_query_filter", json!(newest_filter));
    let newest = QueryInput {
        r#where: newest_filter,
        sort: vec![("timestamp".into(), SortOrder::Desc)],
        limit: Some(100),
        ..QueryInput::default()
    };
    let mut sorted_timings = Vec::with_capacity(args.query_reps);
    for _ in 0..args.query_reps {
        let started = Instant::now();
        let rows = run_query(&runtime, features, newest.clone())?;
        sorted_timings.push(ms(started.elapsed()));
        if rows.len() != 100 {
            return Err(format!("newest-100 query returned {} rows", rows.len()).into());
        }
    }
    let (sorted_partitions, sorted_stats) =
        query_stats(&runtime, features, &newest, &opened, &root)?;
    record(
        &report,
        "sorted_query_partitions_loaded",
        json!(sorted_partitions),
    );
    record(
        &report,
        "sorted_query_median_ms",
        json!(median(&mut sorted_timings)),
    );
    record(
        &report,
        "sorted_query_index_used",
        json!(sorted_stats.index_used),
    );
    record(
        &report,
        "sorted_query_index_sorted",
        json!(sorted_stats.index_sorted),
    );

    // Appends into the last (full-size) partition.
    set_phase(&report, "insert");
    let target = partition_paths.last().ok_or("dataset has no partitions")?;
    let original = fs::read(target)?;
    let last_line = original
        .rsplit(|byte| *byte == b'\n')
        .next()
        .ok_or("empty partition")?;
    let last: Value = serde_json::from_slice(last_line)?;
    let last_ms = parse_iso_ms(last["timestamp"].as_str().ok_or("last row timestamp")?)?;
    let stamps = dataset.insert_timestamps(last_ms, args.inserts);
    let mut rng = SplitMix64(args.seed ^ 0x5eed_0fa9_9e4d);
    let mut insert_ms = Vec::new();
    let mut written = Vec::new();
    let mut read = Vec::new();
    let mut growth = Vec::new();
    let mut line_bytes = Vec::new();
    let mut targets = HashSet::new();
    let budget = Duration::from_secs_f64(args.insert_budget_secs);
    let insert_started = Instant::now();
    let mut budget_hit = false;
    host.take();
    for stamp in &stamps {
        if insert_started.elapsed() > budget {
            budget_hit = true;
            break;
        }
        let row = synthetic_row(*stamp, &mut rng, dataset.month_field);
        line_bytes.push(serde_json::to_string(&row)?.len() as u64 + 1);
        let before = fs::metadata(target)?.len();
        let started = Instant::now();
        runtime
            .mutate(|db| db.create(COLLECTION, row))
            .map_err(tag)?;
        insert_ms.push(ms(started.elapsed()));
        let counters = host.take();
        targets.extend(counters.written_paths.iter().cloned());
        written.push(counters.bytes_written as f64);
        read.push(counters.bytes_read as f64);
        growth.push(fs::metadata(target)?.len().saturating_sub(before) as f64);
        let done = insert_ms.len();
        if done.is_power_of_two() || done % 100 == 0 {
            record(&report, "inserts_done", json!(done));
            record(
                &report,
                "insert_median_ms",
                json!(median(&mut insert_ms.clone())),
            );
            eprintln!(
                "[tsbench] rows={rows} insert {done}/{}: last {:.1} ms",
                stamps.len(),
                insert_ms[done - 1]
            );
        }
    }
    let after = fs::read(target)?;
    record(&report, "inserts_requested", json!(args.inserts));
    record(&report, "inserts_done", json!(insert_ms.len()));
    record(
        &report,
        "insert_budget_secs",
        json!(args.insert_budget_secs),
    );
    record(&report, "insert_budget_hit", json!(budget_hit));
    record(
        &report,
        "insert_target",
        json!(target.file_name().map(|name| name.to_string_lossy())),
    );
    record(&report, "insert_target_bytes_before", json!(original.len()));
    record(&report, "insert_paths_written", json!(targets.len()));
    if let (Some(first), Some(read_first)) = (insert_ms.first(), read.first()) {
        // In lazy mode the first append loads the target partition for the
        // ID check; later appends find it loaded.
        record(&report, "insert_first_ms", json!(first));
        record(&report, "insert_first_bytes_read", json!(read_first));
    }
    if features.lazy {
        let status = runtime
            .lazy_partition_status(COLLECTION)
            .map_err(tag)?
            .ok_or("lazy source has no status")?;
        record(
            &report,
            "partitions_resident_at_end",
            json!(status.loaded.len()),
        );
    }
    if !insert_ms.is_empty() {
        record(&report, "insert_median_ms", json!(median(&mut insert_ms)));
        record(
            &report,
            "insert_p95_ms",
            json!(percentile(&mut insert_ms, 0.95)),
        );
        record(&report, "insert_min_ms", json!(insert_ms[0]));
        record(
            &report,
            "insert_max_ms",
            json!(insert_ms[insert_ms.len() - 1]),
        );
        record(
            &report,
            "insert_bytes_written_median",
            json!(median(&mut written)),
        );
        record(
            &report,
            "insert_bytes_read_median",
            json!(median(&mut read)),
        );
        record(
            &report,
            "insert_file_growth_median",
            json!(median(&mut growth)),
        );
        let mut line_bytes: Vec<f64> = line_bytes.into_iter().map(|b| b as f64).collect();
        record(
            &report,
            "insert_line_bytes_median",
            json!(median(&mut line_bytes)),
        );
    }
    record(
        &report,
        "insert_prefix_preserved",
        json!(after.starts_with(&original)),
    );

    let runtime = if features.lazy {
        // Cold append: reopen, then append into the (now unloaded) target
        // partition. The partition loads for the ID check.
        set_phase(&report, "cold-append");
        runtime.close().map_err(tag)?;
        drop(runtime);
        host.take();
        let started = Instant::now();
        let reopened = NativeRuntime::open_sources_with_host(
            runtime_config(&root, features)?,
            host.clone(),
            runtime_options(features, args)?,
        )
        .map_err(tag)?;
        record(&report, "reopen_ms", json!(ms(started.elapsed())));
        host.take();
        let last = stamps
            .get(insert_ms.len().saturating_sub(1))
            .copied()
            .unwrap_or(last_ms);
        let row = synthetic_row(last + 1, &mut rng, dataset.month_field);
        let started = Instant::now();
        reopened
            .mutate(|db| db.create(COLLECTION, row))
            .map_err(tag)?;
        let cold = host.take();
        record(&report, "cold_append_ms", json!(ms(started.elapsed())));
        record(&report, "cold_append_bytes_read", json!(cold.bytes_read));
        record(
            &report,
            "cold_append_bytes_written",
            json!(cold.bytes_written),
        );
        reopened
    } else {
        runtime
    };

    set_phase(&report, "done");
    record(&report, "peak_rss_mb", json!(proc_status_mb("VmHWM:")));
    record(&report, "status", json!("ok"));
    runtime.close().map_err(tag)?;
    emit(&report);
    Ok(())
}

/// Run one timed query: through the lazy-aware runtime API in lazy mode,
/// through the engine directly (as in steps 1–4) otherwise.
fn run_query(
    runtime: &NativeRuntime,
    features: Features,
    input: QueryInput,
) -> Result<Vec<Value>, BoxError> {
    if features.lazy {
        runtime.query(COLLECTION, input, None).map_err(tag)
    } else {
        runtime
            .read(|db| db.query(COLLECTION, input, None))
            .map_err(tag)
    }
}

/// Partitions the query needed loaded and the engine's plan for it. Lazy
/// mode reads both from the native query stats API
/// (`NativeRuntime::query_with_stats`). Eager modes load every partition at
/// open, so "partitions loaded" counts the partition files read at open; the
/// plan (`index_used`, `candidate_rows`) comes from `Database::explain_query`,
/// which shares the executor's planning functions.
fn query_stats(
    runtime: &NativeRuntime,
    features: Features,
    input: &QueryInput,
    opened: &Counters,
    root: &Path,
) -> Result<(usize, QueryStats), BoxError> {
    if features.lazy {
        let (_, stats) = runtime
            .query_with_stats(COLLECTION, input.clone(), None)
            .map_err(tag)?;
        return Ok((
            stats.partitions_loaded,
            QueryStats {
                index_used: stats.index_used,
                candidate_rows: stats.candidate_rows,
                index_sorted: stats.index_sorted,
            },
        ));
    }
    let stats = runtime
        .read(|db| db.explain_query(COLLECTION, input))
        .map_err(tag)?;
    Ok((opened.partition_paths(root), stats))
}

/// Partition key used for this run.
fn partition_key_label(features: Features) -> &'static str {
    if features.time_bucket {
        "time_bucket:timestamp:month"
    } else {
        "field:month"
    }
}

fn ordered_indexes(features: Features) -> Vec<String> {
    if features.ordered_index {
        vec!["timestamp".to_owned()]
    } else {
        vec![]
    }
}

/// Each later step removes its check here and wires the feature into
/// `runtime_config`, `runtime_options` and `query_stats`.
fn require_supported(_features: Features) -> Result<(), BoxError> {
    Ok(())
}

fn runtime_config(root: &Path, features: Features) -> Result<NativeSourceRuntimeConfig, BoxError> {
    let field = |name: &str, schema: SchemaNode| StructField {
        name: name.into(),
        schema,
    };
    let mut fields = vec![
        field("id", SchemaNode::Str),
        field("timestamp", SchemaNode::Str),
        field("bpm", SchemaNode::Num),
        field("source", SchemaNode::Str),
    ];
    if !features.time_bucket {
        fields.push(field("month", SchemaNode::Str));
    }
    let descriptor = CollectionDescriptor {
        name: COLLECTION.into(),
        schema: SchemaNode::Struct { fields },
        id_strategy: IdStrategy::Provided,
        relationships: vec![],
        indexes: vec![],
        ordered_indexes: ordered_indexes(features),
        unique_fields: vec![],
        before_create_hooks: vec![],
        after_create_hooks: vec![],
        before_update_hooks: vec![],
        after_update_hooks: vec![],
        before_delete_hooks: vec![],
        after_delete_hooks: vec![],
        on_change_hooks: vec![],
        computed_fields: vec![],
        search_index: vec![],
        id_generator: None,
        version: None,
        migrations: vec![],
        append_only: features.append_only,
        duplicate_ids: if features.append_only {
            DuplicateIdPolicy::IgnoreIdentical
        } else {
            DuplicateIdPolicy::Error
        },
        validation_mode: ValidationMode::Strict,
    };
    Ok(NativeSourceRuntimeConfig {
        collections: vec![NativeCollectionConfig::new(descriptor)],
        sources: vec![DatabaseSourceConfig::Partitioned(PartitionedSourceConfig {
            id: COLLECTION.into(),
            collection: COLLECTION.into(),
            root: root.to_string_lossy().into_owned(),
            format: "jsonl".into(),
            partition_by: if features.time_bucket {
                PartitionKey::TimeBucket {
                    field: "timestamp".into(),
                    bucket: TimeBucket::Month,
                }
            } else {
                PartitionKey::Field {
                    field: "month".into(),
                }
            },
            prose: None,
        })],
    })
}

fn runtime_options(
    features: Features,
    args: &Args,
) -> Result<NativeSourceRuntimeOptions, BoxError> {
    let mut lazy_partitions = IndexMap::new();
    if features.lazy {
        // Full scans fail: every timed operation must prune.
        lazy_partitions.insert(
            COLLECTION.to_owned(),
            LazyPartitionPolicy {
                max_loaded_partitions: args.max_loaded_partitions,
                full_scan: FullScanPolicy::Error,
            },
        );
    }
    Ok(NativeSourceRuntimeOptions {
        watch_debounce: None,
        lazy_partitions,
        ..NativeSourceRuntimeOptions::default()
    })
}

