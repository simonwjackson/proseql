//! Time-series benchmark for a partitioned JSONL collection. Synthetic data only.
//!
//! The parent process generates (or reuses) fixed-seed heart-rate rows in the
//! system temp directory, copies them into a fresh work directory per size,
//! and runs each size in a fresh child process so that peak RSS (`VmHWM`) is
//! per size. Each child prints one machine-readable `TSBENCH {json}` line.
//!
//! ```text
//! cargo run --release --manifest-path crates/Cargo.toml -p proseql-native \
//!   --example timeseries_bench -- --rows 140000,1000000,10000000 --years 10
//! ```
//!
//! `--mode` selects cumulative feature sets so later steps switch features on
//! without changing the harness. See `docs/benchmarks/timeseries.md`.

